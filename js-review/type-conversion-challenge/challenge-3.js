//Challenge Set 3: Arrays & Objects
console.log([1] + [2]); // 12
console.log([1, 2] + [3, 4]); // = 1,2 + 3,4 = 1.23,4
console.log([] + []); // blank or empty
console.log([] + {}); // "" + object object = object object
console.log({} + []); // object object + "" = object object
console.log([1] == 1); // true
console.log([1, 2] == "1,2"); //"1,2" == "1,2" // true
